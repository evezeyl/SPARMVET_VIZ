"""Inventory of every key in the deployment files and the app features files (ADR-091).

For each key (flattened, for example features.export_enabled) the script reports which
Python files read its name as a string, split into code that acts on it and code that only
declares or validates it. It is read-only. The result feeds the mapping table of the
configuration rename: a key nobody reads is a candidate for deletion, a key read in the
wrong kind of file is a candidate for moving.

A reader is found by searching the leaf name as a quoted string ("name" or 'name') in
Python files outside tests. This is a heuristic: keys read through a computed name, and
keys read by name from YAML anchors, can be missed, so every "unused" result is a
candidate that a person confirms.

Examples:
  .venv/bin/python assets/scripts/inventory_config_keys.py
  .venv/bin/python assets/scripts/inventory_config_keys.py --out tmpAI/rename/inventory.md
"""

import argparse
import re
import sys
from collections import defaultdict
from pathlib import Path

import yaml

SOURCES = {
    "deployment": ("config/deployment", "*.yaml"),
    "app features": ("config/app_features", "*.yaml"),
}
CODE_DIRS = ("app", "libs", "assets/scripts", "scripts")
# Files that only declare or check keys; they do not act on them.
DECLARE_ONLY = ("persona_validator.py", "sidebar_validator.py", "deployment_error.py")
# Keys whose children are free-form data (labels, lists of panels), not named settings.
OPAQUE = ("workspaces",)


class _Loader(yaml.SafeLoader):
    """Safe loader that also accepts the !include tag used in templates (kept as text)."""


_Loader.add_constructor("!include", lambda loader, node: f"!include {loader.construct_scalar(node)}")


def flatten(node, prefix=""):
    """Yield (dotted_key, value) for every mapping key."""
    if isinstance(node, dict):
        for k, v in node.items():
            key = f"{prefix}.{k}" if prefix else str(k)
            yield key, v
            if str(k) not in OPAQUE or prefix:
                yield from flatten(v, key)


def python_files():
    for d in CODE_DIRS:
        for p in Path(d).rglob("*.py"):
            if "tests" in p.parts or ".venv" in p.parts:
                continue
            yield p


def build_reader_index(names):
    """Map leaf name -> list of (file, line) where it appears as a quoted string."""
    patterns = {n: re.compile(r"""["']""" + re.escape(n) + r"""["']""") for n in names}
    found = defaultdict(list)
    for p in python_files():
        try:
            lines = p.read_text(encoding="utf-8").split("\n")
        except (UnicodeDecodeError, OSError):
            continue
        for i, line in enumerate(lines, 1):
            for n, rx in patterns.items():
                if rx.search(line):
                    found[n].append((str(p), i))
    return found


def classify(hits):
    if not hits:
        return "UNUSED"
    acting = [h for h in hits if not h[0].endswith(DECLARE_ONLY)]
    return "used" if acting else "declared only"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", metavar="PATH", help="write the Markdown report here (default: print)")
    args = ap.parse_args()

    entries = []  # (kind, file, dotted_key, leaf)
    for kind, (folder, pattern) in SOURCES.items():
        for f in sorted(Path(folder).rglob(pattern)):
            try:
                data = yaml.load(f.read_text(encoding="utf-8"), Loader=_Loader)
            except yaml.YAMLError as exc:
                print(f"cannot parse {f}: {exc}", file=sys.stderr)
                continue
            for dotted, _ in flatten(data or {}):
                entries.append((kind, str(f), dotted, dotted.split(".")[-1]))

    leaves = {e[3] for e in entries}
    index = build_reader_index(leaves)

    # One row per (kind, key); list the files that carry it.
    rows = defaultdict(lambda: {"files": set(), "leaf": ""})
    for kind, f, dotted, leaf in entries:
        r = rows[(kind, dotted)]
        r["files"].add(Path(f).name)
        r["leaf"] = leaf

    out = ["# Configuration key inventory", "",
           "Generated by `assets/scripts/inventory_config_keys.py` (read-only). A key is a",
           "heuristic match of its leaf name as a quoted string in Python code outside tests.",
           "Every UNUSED row is a candidate that a person confirms.", ""]
    for kind in SOURCES:
        out += [f"## {kind}", "", "| key | status | read in | carried by |", "|---|---|---|---|"]
        for (k, dotted), r in sorted(rows.items(), key=lambda kv: kv[0][1]):
            if k != kind:
                continue
            hits = index.get(r["leaf"], [])
            status = classify(hits)
            where = ", ".join(sorted({f"{Path(h[0]).name}:{h[1]}" for h in hits})[:3]) or "-"
            files = len(r["files"])
            out.append(f"| `{dotted}` | {status} | {where} | {files} file(s) |")
        out.append("")
    unused = sorted(d for (k, d), r in rows.items() if classify(index.get(r['leaf'], [])) == "UNUSED")
    out += ["## Summary", "", f"- keys in total: {len(rows)}",
            f"- UNUSED candidates: {len(unused)}"]
    out += [f"  - `{u}`" for u in unused]
    text = "\n".join(out) + "\n"
    if args.out:
        Path(args.out).parent.mkdir(parents=True, exist_ok=True)
        Path(args.out).write_text(text)
        print(f"wrote {args.out}")
    else:
        print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
